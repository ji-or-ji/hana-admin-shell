# admin-agent.ps1 -- Hana Admin Shell privileged worker.
#
# Started elevated (UAC) by the Admin Shell app, window hidden. It owns a
# file-based request/response channel under -Root and exits on its own when
# the app stops renewing the lease or the hard lifetime runs out.
#
# Protocol (all files UTF-8 JSON, no BOM):
#   <Root>/req/<nnnnn>-<id>.json   { id, command, cwd, shell, timeoutSec, sessionPath }
#   <Root>/res/<id>.json           { id, exitCode, timedOut, stdout, stderr, startedAt, endedAt, ... }
#   <Root>/state.json              heartbeat written by this process
#   <Root>/lease.json              written by the app: { expiresAt, hardExpiresAt, sessions: [...] }
#   <Root>/stop                    empty file -> exit now
#
# Keep this file pure ASCII: Windows PowerShell 5.1 reads BOM-less script
# files in the console code page, so non-ASCII text here would corrupt.

param(
    [Parameter(Mandatory = $true)][string]$Root,
    [int]$IdleTimeoutSec = 1800,
    [int]$MaxLifeSec = 14400,
    [string]$Token = "",
    [string]$AppVersion = "0"
)

$ErrorActionPreference = "Stop"
$ProgressPreference = "SilentlyContinue"

$ReqDir = Join-Path $Root "req"
$ResDir = Join-Path $Root "res"
$TmpDir = Join-Path $Root "tmp"
$AuditPath = Join-Path $Root "audit.log"
$StatePath = Join-Path $Root "state.json"
$LeasePath = Join-Path $Root "lease.json"
$StopPath = Join-Path $Root "stop"

foreach ($d in @($ReqDir, $ResDir, $TmpDir)) {
    if (-not (Test-Path -LiteralPath $d)) { New-Item -ItemType Directory -Path $d -Force | Out-Null }
}

$Utf8NoBom = New-Object System.Text.UTF8Encoding($false)

function Write-JsonFile {
    param([string]$Path, $Object)
    $tmp = "$Path.tmp"
    [IO.File]::WriteAllText($tmp, ($Object | ConvertTo-Json -Depth 8 -Compress), $Utf8NoBom)
    if (Test-Path -LiteralPath $Path) { Remove-Item -LiteralPath $Path -Force -ErrorAction SilentlyContinue }
    Move-Item -LiteralPath $tmp -Destination $Path -Force
}

# Heartbeat writer: fixed 4KB, overwrite in place.
# tmp + rename would create/delete a file and touch the directory entry on every beat,
# which NTFS journals as three metadata records. Overwriting the same cluster keeps the
# file size constant, so an idle heartbeat costs one cluster and nothing else.
function Write-StateFile {
    param([string]$Path, $Object)
    $json = ($Object | ConvertTo-Json -Depth 8 -Compress)
    $bytes = $Utf8NoBom.GetBytes($json)
    $size = 4096
    if ($bytes.Length + 8 -gt $size) {
        $size = [int]([math]::Ceiling(($bytes.Length + 8) / 4096.0) * 4096)
    }
    $buf = New-Object byte[] $size
    for ($i = 0; $i -lt $size; $i++) { $buf[$i] = 0x20 }
    [Array]::Copy($bytes, $buf, $bytes.Length)
    $fs = [IO.File]::Open($Path, [IO.FileMode]::OpenOrCreate, [IO.FileAccess]::Write, [IO.FileShare]::ReadWrite)
    try {
        if ($fs.Length -ne $size) { $fs.SetLength($size) }
        $fs.Position = 0
        $fs.Write($buf, 0, $size)
        $fs.Flush()
    } finally {
        $fs.Dispose()
    }
}

function Read-JsonFile {
    param([string]$Path)
    $raw = [IO.File]::ReadAllText($Path, $Utf8NoBom)
    if ([string]::IsNullOrWhiteSpace($raw)) { return $null }
    $raw = $raw.TrimStart([char]0xFEFF)
    return $raw | ConvertFrom-Json
}

function Append-Audit {
    param($Record)
    try {
        $line = ($Record | ConvertTo-Json -Depth 6 -Compress) + "`n"
        [IO.File]::AppendAllText($AuditPath, $line, $Utf8NoBom)
    } catch { }
}

# Decode captured bytes: strict UTF-8 first, fall back to the local ANSI code page.
function Convert-OutputBytes {
    param([byte[]]$Bytes, [int]$Count)
    if ($null -eq $Bytes -or $Count -le 0) { return "" }
    $strict = New-Object System.Text.UTF8Encoding($false, $true)
    try {
        return $strict.GetString($Bytes, 0, $Count)
    } catch {
        try {
            $ansi = [System.Text.Encoding]::GetEncoding([System.Globalization.CultureInfo]::CurrentCulture.TextInfo.ANSICodePage)
            return $ansi.GetString($Bytes, 0, $Count)
        } catch {
            return [System.Text.Encoding]::UTF8.GetString($Bytes, 0, $Count)
        }
    }
}

function Invoke-OneRequest {
    param($Request)

    $id = [string]$Request.id
    $command = [string]$Request.command
    $shell = "cmd"
    if ($Request.shell -eq "powershell") { $shell = "powershell" }
    elseif ($Request.shell -eq "auto") {
        if ($command -match '^\s*(\$|if\s|foreach|while|Get-|Set-|New-|Remove-|Write-|Start-|\||\&)') { $shell = "powershell" }
    }
    $cwd = [string]$Request.cwd
    if ([string]::IsNullOrWhiteSpace($cwd) -or -not (Test-Path -LiteralPath $cwd)) { $cwd = $env:USERPROFILE }
    $timeoutSec = 0
    if ($Request.timeoutSec) { $timeoutSec = [int]$Request.timeoutSec }
    if ($timeoutSec -le 0) { $timeoutSec = 120 }

    if ($shell -eq "powershell") {
        $exe = "powershell.exe"
        $scriptFile = Join-Path $TmpDir ("$id.ps1")
        $scriptText = "# generated by admin-agent
" + $command
        $bom = New-Object System.Text.UTF8Encoding($true)
        [IO.File]::WriteAllText($scriptFile, $scriptText, $bom)
        $argLine = '-NoProfile -NonInteractive -ExecutionPolicy Bypass -File "' + $scriptFile + '"'
    } else {
        $exe = "cmd.exe"
        $scriptFile = Join-Path $TmpDir ("$id.cmd")
        $ansi = [System.Text.Encoding]::GetEncoding([System.Globalization.CultureInfo]::CurrentCulture.TextInfo.ANSICodePage)
        [IO.File]::WriteAllText($scriptFile, $command, $ansi)
        $argLine = '/d /s /c ""' + $scriptFile + '""'
    }

    $startedAt = [DateTimeOffset]::UtcNow.ToUnixTimeMilliseconds()
    $result = [ordered]@{
        id           = $id
        shell        = $shell
        cwd          = $cwd
        exitCode     = $null
        timedOut     = $false
        stdout       = ""
        stderr       = ""
        startedAt    = $startedAt
        endedAt      = $null
        durationMs   = $null
        error        = $null
    }

    $proc = $null
    $scriptFile = $null
    try {
        $psi = New-Object System.Diagnostics.ProcessStartInfo
        $psi.FileName = $exe
        $psi.Arguments = $argLine
        $psi.WorkingDirectory = $cwd
        $psi.UseShellExecute = $false
        $psi.RedirectStandardOutput = $true
        $psi.RedirectStandardError = $true
        $psi.CreateNoWindow = $true

        $proc = New-Object System.Diagnostics.Process
        $proc.StartInfo = $psi
        [void]$proc.Start()

        $outBuf = New-Object System.IO.MemoryStream
        $errBuf = New-Object System.IO.MemoryStream
        $tOut = $proc.StandardOutput.BaseStream.CopyToAsync($outBuf)
        $tErr = $proc.StandardError.BaseStream.CopyToAsync($errBuf)

        $finished = $proc.WaitForExit($timeoutSec * 1000)
        if (-not $finished) {
            $result.timedOut = $true
            try { & taskkill.exe /T /F /PID $proc.Id 2>&1 | Out-Null } catch { }
            try { $proc.Kill() } catch { }
            [void]$proc.WaitForExit(5000)
        }
        try { [void]$tOut.Wait(3000) } catch { }
        try { [void]$tErr.Wait(3000) } catch { }

        $result.exitCode = $proc.ExitCode
        $outBytes = $outBuf.ToArray()
        $errBytes = $errBuf.ToArray()
        $result.stdout = Convert-OutputBytes -Bytes $outBytes -Count $outBytes.Length
        $result.stderr = Convert-OutputBytes -Bytes $errBytes -Count $errBytes.Length
        $outBuf.Dispose()
        $errBuf.Dispose()
    } catch {
        $result.error = [string]$_.Exception.Message
    } finally {
        if ($null -ne $proc) { try { $proc.Dispose() } catch { } }
        if ($scriptFile) { try { Remove-Item -LiteralPath $scriptFile -Force -ErrorAction SilentlyContinue } catch { } }
    }

    $result.endedAt = [DateTimeOffset]::UtcNow.ToUnixTimeMilliseconds()
    $result.durationMs = $result.endedAt - $startedAt
    return $result
}

# ---------------------------------------------------------------- start up

$isAdmin = $false
try {
    $isAdmin = ([Security.Principal.WindowsPrincipal][Security.Principal.WindowsIdentity]::GetCurrent()).IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)
} catch { }

$startedAt = [DateTimeOffset]::UtcNow.ToUnixTimeMilliseconds()
$hardDeadline = $startedAt + ($MaxLifeSec * 1000)
$lastActive = $startedAt
$processed = 0
$me = [System.Security.Principal.WindowsIdentity]::GetCurrent()

$state = [ordered]@{
    alive       = $true
    pid         = $PID
    token       = $Token
    elevated    = $isAdmin
    user        = $me.Name
    appVersion  = $AppVersion
    startedAt   = $startedAt
    lastBeatAt  = $startedAt
    idleTimeoutSec = $IdleTimeoutSec
    hardDeadline   = $hardDeadline
    processed   = 0
    exitReason  = $null
}
Write-StateFile -Path $StatePath -Object $state
Append-Audit @{ t = $startedAt; event = "start"; pid = $PID; elevated = $isAdmin; user = $me.Name }

$exitReason = "unknown"
$lastBeat = 0
$startFence = $startedAt

while ($true) {
    $now = [DateTimeOffset]::UtcNow.ToUnixTimeMilliseconds()

    if (Test-Path -LiteralPath $StopPath) { $exitReason = "stop-requested"; break }
    if ($now -ge $hardDeadline) { $exitReason = "max-life-reached"; break }

    # Lease: the app keeps it fresh while at least one session holds the channel.
    $leaseOk = $true
    if (Test-Path -LiteralPath $LeasePath) {
        try {
            $lease = Read-JsonFile -Path $LeasePath
            if ($null -ne $lease) {
                if ($lease.hardExpiresAt -and ($now -ge [int64]$lease.hardExpiresAt)) { $exitReason = "lease-expired"; break }
                if ($lease.expiresAt -and ($now -ge [int64]$lease.expiresAt)) { $exitReason = "lease-expired"; break }
                if ($lease.revoked -eq $true) { $exitReason = "lease-revoked"; break }
            }
        } catch { $leaseOk = $false }
    } elseif (($now - $startFence) -gt 15000) {
        # No lease file at all for a while: the app died or never wrote one.
        $exitReason = "lease-missing"
        break
    }

    if (($now - $lastActive) -gt ($IdleTimeoutSec * 1000)) { $exitReason = "idle-timeout"; break }

    $handled = $false
    try {
        $pending = @(Get-ChildItem -LiteralPath $ReqDir -Filter "*.json" -File -ErrorAction SilentlyContinue | Sort-Object Name)
        if ($pending.Count -gt 0) {
            $file = $pending[0]
            $req = $null
            try { $req = Read-JsonFile -Path $file.FullName } catch { $req = $null }
            Remove-Item -LiteralPath $file.FullName -Force -ErrorAction SilentlyContinue
            if ($null -ne $req -and $req.id) {
                Append-Audit @{ t = $now; event = "exec"; id = [string]$req.id; command = [string]$req.command; shell = [string]$req.shell; session = [string]$req.sessionPath }
                $res = Invoke-OneRequest -Request $req
                $resPath = Join-Path $ResDir ("$($req.id).json")
                Write-JsonFile -Path $resPath -Object $res
                Append-Audit @{ t = $res.endedAt; event = "done"; id = [string]$req.id; exitCode = $res.exitCode; timedOut = $res.timedOut; durationMs = $res.durationMs }
                $processed = $processed + 1
                $lastActive = [DateTimeOffset]::UtcNow.ToUnixTimeMilliseconds()
                $handled = $true
            }
        }
    } catch {
        Append-Audit @{ t = $now; event = "error"; message = [string]$_.Exception.Message }
    }

    if ((-not $handled) -and (($now - $lastBeat) -gt 15000)) {
        $state.lastBeatAt = $now
        $state.processed = $processed
        Write-StateFile -Path $StatePath -Object $state
        $lastBeat = $now
    }

    Start-Sleep -Milliseconds 200
}

# ---------------------------------------------------------------- shutdown

$endedAt = [DateTimeOffset]::UtcNow.ToUnixTimeMilliseconds()
$state.alive = $false
$state.exitedAt = $endedAt
$state.exitReason = $exitReason
$state.processed = $processed
Write-StateFile -Path $StatePath -Object $state
Append-Audit @{ t = $endedAt; event = "exit"; reason = $exitReason; processed = $processed }

try {
    Get-ChildItem -LiteralPath $ReqDir -Filter "*.json" -File -ErrorAction SilentlyContinue | Remove-Item -Force -ErrorAction SilentlyContinue
    Get-ChildItem -LiteralPath $TmpDir -File -ErrorAction SilentlyContinue | Remove-Item -Force -ErrorAction SilentlyContinue
} catch { }
